const questionWords = [];
function collectQuestionWords(value, pathName = "") {
  if (Array.isArray(value)) return value.forEach((item, index) => collectQuestionWords(item, `${pathName}[${index}]`));
  if (value && typeof value === "object") {
    return Object.entries(value).forEach(([key, child]) => collectQuestionWords(child, pathName ? `${pathName}.${key}` : key));
  }
  if (typeof value === "string") {
    for (const word of value.split(/[^A-Za-z0-9?]+/).filter((item) => item.includes("?") && item !== "?")) {
      questionWords.push([pathName, word]);
    }
  }
  return undefined;
}
