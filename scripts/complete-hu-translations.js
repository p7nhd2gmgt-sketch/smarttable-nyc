function translateFallback(text) {
  if (!text) return text;
  if (Object.prototype.hasOwnProperty.call(exact, text)) return exact[text];
  let translated = text;
  for (const [from, to] of phraseReplacements.sort((a, b) => b[0].length - a[0].length)) {
    translated = translated.replace(new RegExp(`\\b${from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "gi"), to);
  }
  if (translated === text) return text;
  return translated;
}

const callPattern = /t\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]*)['"]\s*\)/g;
let match;
let added = 0;
while ((match = callPattern.exec(appSource))) {
  const [, key, fallback] = match;
  if (!fallback || fallback.startsWith("/")) continue;
  if (locale[key] && locale[key] !== fallback && !exact[fallback]) continue;
  const exactTranslation = Object.prototype.hasOwnProperty.call(exact, fallback) ? exact[fallback] : null;
  const literalTranslation = locale._literals?.[fallback];
  const translated = exactTranslation !== null
    ? exactTranslation
    : literalTranslation && literalTranslation !== fallback
    ? literalTranslation
    : translateFallback(fallback);
  locale[key] = translated;
  added += 1;
}

locale._literals = locale._literals || {};
for (const [fallback, translation] of Object.entries(exact)) {
  locale._literals[fallback] = translation;
}

function escapeNonAscii(json) {
  return json.replace(/[^\x00-\x7F]/g, (char) => {
    const hex = char.charCodeAt(0).toString(16).padStart(4, "0");
    return `\\u${hex}`;
  });
}

